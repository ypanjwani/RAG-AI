// Turns vega-interpreter (an ES module) into a plain script for Code Lab 2.0's widget frame: shared/vega-interpreter.js.
// The frame's Content-Security-Policy blocks eval, and Vega compiles chart formulas with new Function unless it is
// given this interpreter (vega.parse(spec, null, {ast: true}) + View option expr), so charts would stay blank.
// The module imports three helpers from vega-util, which the Vega browser build already exposes on window.vega.
//
//   node scripts/vendor-vega.mjs           write the file
//   node scripts/vendor-vega.mjs --check   fail if it is out of date
//
// Run it after upgrading vega-interpreter (pinned in package.json).

import { readFileSync, writeFileSync, existsSync } from "node:fs";

const SRC = new URL("../node_modules/vega-interpreter/build/vega-interpreter.js", import.meta.url);
const OUT = new URL("../shared/vega-interpreter.js", import.meta.url);
const IMPORT = "import { ascending, isString, DisallowedObjectProperties } from 'vega-util';";
const EXPORT = "export { expression as expressionInterpreter };";

const pkg = JSON.parse(readFileSync(new URL("../node_modules/vega-interpreter/package.json", import.meta.url), "utf8"));
const src = readFileSync(SRC, "utf8");
const lines = src.split(/\r?\n/);
// Fail loudly if a new version changes its imports or exports: the conversion below would then be wrong.
if (lines.filter((l) => l.startsWith("import ")).join("\n") !== IMPORT || lines.filter((l) => l.startsWith("export ")).join("\n") !== EXPORT) {
  console.error(`vendor-vega: vega-interpreter@${pkg.version} has different imports or exports; update this script.`);
  process.exit(1);
}
const body = lines.filter((l) => l !== IMPORT && l !== EXPORT).join("\n").trim();

const out = `// Generated by scripts/vendor-vega.mjs from vega-interpreter@${pkg.version} (${pkg.license}, the Vega project). Do not edit.
// Vega's chart formulas evaluated without eval, so charts draw under the widget frame's Content-Security-Policy.
// Load after vega.min.js; sets window.vegaInterpreter (used by XW.vega in shared/widget-kit.js).
(function () {
const { ascending, isString, DisallowedObjectProperties } = window.vega;

${body}

window.vegaInterpreter = expression;
})();
`;

if (process.argv.includes("--check")) {
  if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== out) {
    console.error("shared/vega-interpreter.js is out of date: run node scripts/vendor-vega.mjs");
    process.exit(1);
  }
  console.log("shared/vega-interpreter.js is up to date.");
} else {
  writeFileSync(OUT, out);
  console.log(`Wrote shared/vega-interpreter.js from vega-interpreter@${pkg.version}.`);
}
